#!/usr/bin/env node
// Builds the agent skill that ships with GeoCarto:
//  1. bundles src/skill/validateCli.ts (which imports the app's own schema and
//     parsers) into skills/geocarto-maps/scripts/validate.mjs — a single file
//     with no dependencies, runnable with plain `node`;
//  2. zips the skill folder to public/geocarto-skill.zip, which the app offers
//     for download in Settings.
// Runs as part of `npm run build`, so the shipped validator always matches the
// app it ships with.

import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { crc32 } from 'node:zlib';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = join(root, 'skills/geocarto-maps');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

await build({
  entryPoints: [join(root, 'src/skill/validateCli.ts')],
  outfile: join(skillDir, 'scripts/validate.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  alias: { '@': join(root, 'src') },
  banner: { js: `// GeoCarto ${version} — generated by scripts/build-skill.mjs; do not edit.` },
  logLevel: 'warning',
});

function listFiles(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? listFiles(path) : [path];
    });
}

// A minimal "stored" (uncompressed) zip: the skill is a few small text files,
// and writing the format directly avoids a dependency for one archive.
// A fixed, valid timestamp (1980-01-01) keeps the archive byte-for-byte reproducible.
const DOS_DATE = (1 << 5) | 1;

function zip(entries) {
  const chunks = [];
  const central = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const nameBytes = Buffer.from(name, 'utf8');
    const header = Buffer.alloc(30);
    header.writeUInt32LE(0x04034b50, 0);
    header.writeUInt16LE(20, 4); // version needed
    header.writeUInt16LE(0x0800, 6); // UTF-8 names
    header.writeUInt16LE(DOS_DATE, 12);
    header.writeUInt32LE(crc32(data), 14);
    header.writeUInt32LE(data.length, 18);
    header.writeUInt32LE(data.length, 22);
    header.writeUInt16LE(nameBytes.length, 26);
    chunks.push(header, nameBytes, data);

    const record = Buffer.alloc(46);
    record.writeUInt32LE(0x02014b50, 0);
    record.writeUInt16LE(20, 4);
    record.writeUInt16LE(20, 6);
    record.writeUInt16LE(0x0800, 8);
    record.writeUInt16LE(DOS_DATE, 14);
    record.writeUInt32LE(crc32(data), 16);
    record.writeUInt32LE(data.length, 20);
    record.writeUInt32LE(data.length, 24);
    record.writeUInt16LE(nameBytes.length, 28);
    record.writeUInt32LE(offset, 42);
    central.push(record, nameBytes);
    offset += header.length + nameBytes.length + data.length;
  }
  const directory = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...chunks, directory, end]);
}

const entries = listFiles(skillDir).map((path) => ({
  // Forward slashes and a top-level folder, so it unpacks as `geocarto-maps/`.
  name: `geocarto-maps/${relative(skillDir, path).split('\\').join('/')}`,
  data: readFileSync(path),
}));
mkdirSync(join(root, 'public'), { recursive: true });
writeFileSync(join(root, 'public/geocarto-skill.zip'), zip(entries));
console.log(`Skill built: ${entries.length} files → public/geocarto-skill.zip`);
